import api from "./api";

const galleryService = {

    /*
    |--------------------------------------------------------------------------
    | Get All Gallery
    |--------------------------------------------------------------------------
    */

    getAll(params = {}) {

        return api.get("/gallery", {
            params,
        });

    },


    /*
    |--------------------------------------------------------------------------
    | Get Gallery Statistics
    |--------------------------------------------------------------------------
    */

    getStatistics() {

        return api.get("/gallery/statistics");

    },


    /*
    |--------------------------------------------------------------------------
    | Get Gallery By ID
    |--------------------------------------------------------------------------
    */

    getById(id) {

        return api.get(`/gallery/${id}`);

    },


    /*
    |--------------------------------------------------------------------------
    | Create Gallery
    |--------------------------------------------------------------------------
    */

    create(data) {

        return api.post(
            "/gallery",
            data,
            {
                headers: {
                    "Content-Type": "multipart/form-data",
                },
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Update Gallery
    |--------------------------------------------------------------------------
    */

    update(id, data) {

        return api.put(
            `/gallery/${id}`,
            data,
            {
                headers: {
                    "Content-Type": "multipart/form-data",
                },
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Delete Gallery
    |--------------------------------------------------------------------------
    */

    delete(id) {

        return api.delete(`/gallery/${id}`);

    },

};

export default galleryService;
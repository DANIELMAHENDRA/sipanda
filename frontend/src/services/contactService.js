import api from "./api";

const contactService = {

    /*
    |--------------------------------------------------------------------------
    | Public
    |--------------------------------------------------------------------------
    */

    getContact() {

        return api.get("/contact");

    },

    /*
    |--------------------------------------------------------------------------
    | Admin
    |--------------------------------------------------------------------------
    */

    update(data) {

        return api.put("/contact", data);

    },

};

export default contactService;